def _normalize(text: str) -> str:
    return re.sub(r"\s+", " ", (text or "").lower().replace("\u200c", " ").replace("ي", "ی").replace("ك", "ک")).strip()


def classify_fa(title: str, summary: str = "") -> tuple[list[str], list[str]]:
    text = f" {_normalize(title)} {_normalize(summary)} "
    categories = []
    for category, keywords in FA_CATEGORY_RULES.items():
        if any(_normalize(keyword) in text for keyword in keywords):
            categories.append(category)

    topics = []
    for topic, keywords in FA_TOPIC_TERMS.items():
        if any(_normalize(keyword) in text for keyword in keywords):
            topics.append(topic)

    return categories[:10], topics[:14]
